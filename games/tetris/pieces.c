#include "pieces.h"

#include "tetris.h"

#include <stdint.h>

// every rotation precomputed in rom; one row per piece, 4 rotations x 4 cells
static const uint8_t kShapes[kPieceCount][kRotCount * kPieceSprites] = {
    {0x10, 0x11, 0x12, 0x13, 0x02, 0x12, 0x22, 0x32, 0x20, 0x21, 0x22, 0x23, 0x01, 0x11, 0x21, 0x31}, // i
    {0x01, 0x02, 0x11, 0x12, 0x01, 0x02, 0x11, 0x12, 0x01, 0x02, 0x11, 0x12, 0x01, 0x02, 0x11, 0x12}, // o
    {0x01, 0x10, 0x11, 0x12, 0x01, 0x11, 0x12, 0x21, 0x10, 0x11, 0x12, 0x21, 0x01, 0x10, 0x11, 0x21}, // t
    {0x01, 0x02, 0x10, 0x11, 0x01, 0x11, 0x12, 0x22, 0x11, 0x12, 0x20, 0x21, 0x00, 0x10, 0x11, 0x21}, // s
    {0x00, 0x01, 0x11, 0x12, 0x02, 0x11, 0x12, 0x21, 0x10, 0x11, 0x21, 0x22, 0x01, 0x10, 0x11, 0x20}, // z
    {0x00, 0x10, 0x11, 0x12, 0x01, 0x02, 0x11, 0x21, 0x10, 0x11, 0x12, 0x22, 0x01, 0x11, 0x20, 0x21}, // j
    {0x02, 0x10, 0x11, 0x12, 0x01, 0x11, 0x21, 0x22, 0x10, 0x11, 0x12, 0x20, 0x00, 0x01, 0x11, 0x21}, // l
};

static uint8_t rng_state;

const uint8_t* pieces_shape(uint8_t piece, uint8_t rot) {
    return &kShapes[piece][(uint8_t)(rot << 2)];
}

void pieces_seed(uint8_t seed) {
    rng_state = seed;
}

uint8_t pieces_next(void) {
    rng_state = (uint8_t)(rng_state * kRngMul + kRngAdd);
    return (uint8_t)(rng_state % kPieceCount);
}
