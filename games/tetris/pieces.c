static uint8_t rng_state;

const uint8_t* pieces_shape(uint8_t piece, uint8_t rot) {
    // (piece * 4 + rot) * 4 tops out at 108, so the whole index fits a byte
    uint8_t slot = (uint8_t)((uint8_t)((uint8_t)(piece << 2) + rot) << 2);
    return &kShapes[slot];
}

void pieces_seed(uint8_t seed) {
    rng_state = seed;
}

uint8_t pieces_next(void) {
    rng_state = (uint8_t)(rng_state * kRngMul + kRngAdd);
    return (uint8_t)(rng_state % kPieceCount);
}
